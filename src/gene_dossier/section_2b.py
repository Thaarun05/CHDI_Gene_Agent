def figure_status_from_panels(panel_status: dict[str, str]) -> str:
    """Map panel success flags to a figure rendering status string."""
    human_ok = panel_status.get("human") == "success"
    mouse_ok = panel_status.get("mouse") == "success"
    if human_ok and mouse_ok:
        return "success_two_panels"
    if human_ok:
        return "success_human_only"
    if mouse_ok:
        return "success_mouse_only"
    return "unavailable_no_panels"


