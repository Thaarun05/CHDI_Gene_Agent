@dataclass(frozen=True)
class Section2bConfig:
    donor_well_known_file_ids: tuple[int, ...] = (
        allen_human_rnaseq.DEFAULT_DONOR_WELL_KNOWN_FILE_IDS
    )
    exclude_rnaseq_technical_replicates: bool = True
    allen_probe_id: int | None = None
    probe_selection_policy: str = "explicit_or_single_probe"
    category_policy: str = "threshold_policy_unresolved"
    plot_dpi: int = 180
    max_expression_attempts: int = allen_brain.DEFAULT_MAX_EXPRESSION_ATTEMPTS
    retry_sleep_seconds: float = allen_brain.DEFAULT_RETRY_SLEEP_SECONDS

    def __post_init__(self) -> None:
        if tuple(self.donor_well_known_file_ids) != tuple(
            allen_human_rnaseq.DEFAULT_DONOR_WELL_KNOWN_FILE_IDS
        ):
            raise ValueError(
                "Section 2b requires donor IDs "
                f"{allen_human_rnaseq.DEFAULT_DONOR_WELL_KNOWN_FILE_IDS!r}; "
                f"got {self.donor_well_known_file_ids!r}"
            )
        if self.probe_selection_policy not in {
            "explicit_or_single_probe",
            "unresolved",
        }:
            raise ValueError(
                f"Unsupported probe_selection_policy: {self.probe_selection_policy!r}"
            )
        if self.category_policy != "threshold_policy_unresolved":
            raise ValueError(
                f"Unsupported category_policy: {self.category_policy!r}"
            )
        if self.allen_probe_id is not None and int(self.allen_probe_id) <= 0:
            raise ValueError("allen_probe_id must be a positive integer when set")
        if int(self.plot_dpi) < 72:
            raise ValueError("plot_dpi must be >= 72")
        if int(self.max_expression_attempts) < 1:
            raise ValueError("max_expression_attempts must be >= 1")


